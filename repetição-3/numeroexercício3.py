#3-Faça um algoritmo que receba um número e mostre uma mensagem caso este número seja  maior que 80,
#  menor que 25 ou igual a 40. 
numero = int(input("escreva um numero"))
if numero > 80:
    print ("acima")
elif numero < 25:
    print ("abaixo")
elif numero == 40:
    print("exato")
else:
    print ("sla man")

